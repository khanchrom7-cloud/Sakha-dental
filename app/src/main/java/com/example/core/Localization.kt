package com.example.core

enum class AppLanguage(
    val code: String,
    val nativeLabel: String,
    val isRtl: Boolean
) {
    DARI("fa", "دری", true),
    PASHTO("ps", "پښتو", true),
    ENGLISH("en", "English", false);

    companion object {
        fun fromCode(raw: String): AppLanguage =
            entries.firstOrNull { it.name.equals(raw, ignoreCase = true) || it.code.equals(raw, ignoreCase = true) } ?: DARI
    }
}

